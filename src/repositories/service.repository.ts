import type { PrismaClient } from '@prisma/client';
import type { SqliteStore } from '../storage/sqlite.js';
import type { StorageDriverKind } from '../storage/driver-registry.js';
import { createServiceStorageDriver, type ServiceStorageDriver } from './drivers/service.drivers.js';

/** An enrolled Service Provider. Its key is in did_keys, never here. */
export interface ServiceRecord {
  id: string;
  did: string;
  name: string;
  domain: string;
  /** Any one of these is enough. Stored space-joined in the `required_scope` column. */
  requiredScopes: string[];
  description: string | null;
  framework: string | null;
  createdAt: Date;
  revokedAt: Date | null;
}

export interface ServiceCreateData {
  /** Generated by the caller, because a did:web may be derived from it before the row exists. */
  id: string;
  did: string;
  name: string;
  domain: string;
  requiredScopes: string[];
  description: string | null;
  framework: string | null;
}

/**
 * ServiceRepository is a thin delegator over a ServiceStorageDriver — see
 * storage/driver-registry.ts for the pattern. The (prisma?, sqlite?)
 * constructor signature matches every other repository here on purpose.
 */
export class ServiceRepository {
  private readonly driver: ServiceStorageDriver;

  constructor(
    private readonly prisma?: PrismaClient,
    private readonly sqlite?: SqliteStore,
  ) {
    this.driver = createServiceStorageDriver(this.resolveDriverKind(), { prisma, sqlite });
  }

  private resolveDriverKind(): StorageDriverKind {
    if (this.prisma) return 'postgres';
    if (this.sqlite) return 'sqlite';
    return 'memory';
  }

  async create(data: ServiceCreateData): Promise<ServiceRecord> {
    return this.driver.create(data);
  }

  async findById(id: string): Promise<ServiceRecord | null> {
    return this.driver.findById(id);
  }

  async findByDid(did: string): Promise<ServiceRecord | null> {
    return this.driver.findByDid(did);
  }

  async findByName(name: string): Promise<ServiceRecord | null> {
    return this.driver.findByName(name);
  }

  /** Newest first. */
  async list(): Promise<ServiceRecord[]> {
    return this.driver.list();
  }

  /** The DID document stays resolvable: revocation is about this registry, not the identity. */
  async revoke(id: string): Promise<void> {
    return this.driver.revoke(id);
  }
}
